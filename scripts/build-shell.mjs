import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, mkdirSync, copyFileSync, writeFileSync, readdirSync, unlinkSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
if (process.platform !== 'win32') process.exit(0);
const stableWrite=(path,text)=>{try{if(readFileSync(path,'utf8')===text)return;}catch(error){if(error.code!=='ENOENT')throw error;}writeFileSync(path,text);};
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const release=process.argv.includes('--release') || process.env.TAURI_ENV_DEBUG==='false';
const args=['build','--manifest-path',join(root,'windows-shell','Cargo.toml'),'--locked'];
if(release) args.push('--release');
const result=spawnSync('cargo',args,{stdio:'inherit',cwd:root});
if(result.error) throw result.error;if(result.status!==0)process.exit(result.status??1);
const source=join(root,'windows-shell','target',release?'release':'debug','packit_shell.dll');
const hash=createHash('sha256').update(readFileSync(source)).digest('hex');
const filename=`packit_shell_v4_${hash.slice(0,12)}.dll`;
for(const directory of [join(root,'src-tauri','vendor','shell'),join(root,'src-tauri','target',release?'release':'debug','vendor','shell')]){
 mkdirSync(directory,{recursive:true});copyFileSync(source,join(directory,filename));
 stableWrite(join(directory,'manifest.json'),JSON.stringify({filename,sha256:hash},null,2)+'\n');
 if(directory===join(root,'src-tauri','vendor','shell')) stableWrite(join(directory,'installer-shell.nsh'),`; Generated by build-shell.mjs; do not edit.\n!define PACKIT_SHELL_FILENAME "${filename}"\n`);
}
const sourceDirectory=join(root,'src-tauri','vendor','shell');
for(const name of readdirSync(sourceDirectory))if(/^packit_shell_v4_[a-f0-9]{12}\.dll$/.test(name)&&name!==filename){try{unlinkSync(join(sourceDirectory,name));}catch(error){if(error.code!=='EPERM'&&error.code!=='EBUSY')throw error;}}
console.log(`PACKIT shell: ${filename}`);
